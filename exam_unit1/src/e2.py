def tri_shape(A, B, C):
    ab, bc, ca = [simplify(dist(P, Q_) ** 2) for P, Q_ in [(A, B), (B, C), (C, A)]]
    if ab == bc == ca:
        return '정삼각형'
    if ab + ca == bc:
        return 'A직각' + ('이등변' if ab == ca else '')
    if ab + bc == ca:
        return 'B직각' + ('이등변' if ab == bc else '')
    if bc + ca == ab:
        return 'C직각' + ('이등변' if bc == ca else '')
    return '기타'


